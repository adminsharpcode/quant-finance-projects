"""
Institutional Quantitative Metrics Suite
-----------------------------------------
Implements hedge fund-grade statistical and risk analytics:
1. Probabilistic Sharpe Ratio (PSR) - Marcos López de Prado (2012)
2. Deflated Sharpe Ratio (DSR) - Bailey & López de Prado (2014)
   Accounts for selection bias, number of trials (N=1,297), non-normality, and sample length.
3. Family-Wise Error Rate (Bonferroni) and False Discovery Rate (Benjamini-Hochberg)
4. Comprehensive Downside & Tail Risk Suite:
   - Sortino Ratio (Downside deviation MAR=0)
   - Calmar Ratio (Annualized Return / Max Drawdown)
   - Omega Ratio (Gains vs Losses above threshold)
   - Jack Schwager's Gain-to-Pain Ratio
   - Ulcer Index & Martin Ratio
   - Historical VaR (95%, 99%) & Conditional VaR (Expected Shortfall)
   - Conditional Drawdown at Risk (CDaR 95%)
   - Return Skewness & Excess Kurtosis
"""

import math
import numpy as np
import scipy.stats as stats
from typing import Dict, Any, List, Union, Tuple, Optional


def compute_probabilistic_sharpe_ratio(
    sr: float,
    sr_benchmark: float = 0.0,
    n_obs: int = 100,
    skew: float = 0.0,
    kurt: float = 3.0
) -> float:
    """
    Computes the Probabilistic Sharpe Ratio (PSR) developed by Marcos López de Prado (2012).
    Evaluates the probability that the true Sharpe ratio exceeds sr_benchmark,
    taking into account sample length, return skewness, and non-excess kurtosis (normal=3.0).
    
    PSR = Phi( (sr - sr_benchmark) * sqrt(T - 1) / sqrt(1 - skew*sr + ((kurt - 1)/4)*sr^2) )
    """
    if n_obs <= 2:
        return 0.5
    
    # Ensure kurt is non-excess kurtosis (standard normal = 3.0)
    if kurt < 1.0:
        kurt = 3.0
        
    denom_sq = 1.0 - (skew * sr) + ((kurt - 1.0) / 4.0) * (sr ** 2)
    if denom_sq <= 1e-12:
        denom_sq = 1e-12
        
    denom = math.sqrt(denom_sq)
    z_stat = (sr - sr_benchmark) * math.sqrt(n_obs - 1) / denom
    
    psr = float(stats.norm.cdf(z_stat))
    return min(1.0, max(0.0, psr))


def compute_expected_max_sharpe(
    n_trials: int,
    var_sr: float,
    mean_sr: float = 0.0
) -> float:
    """
    Computes the expected maximum Sharpe ratio under the null hypothesis of zero alpha,
    given N independent or correlated trials (Bailey & López de Prado, 2014).
    
    E[max_N] ≈ sqrt(var_sr) * [ (1 - gamma) * Phi^{-1}(1 - 1/N) + gamma * Phi^{-1}(1 - 1/(N*e)) ]
    where gamma is the Euler-Mascheroni constant ≈ 0.5772156649.
    """
    if n_trials <= 1:
        return max(0.0, mean_sr)
    
    std_sr = math.sqrt(max(1e-10, var_sr))
    euler_gamma = float(np.euler_gamma)
    e = math.e
    
    # Quantiles under standard normal
    q1 = float(stats.norm.ppf(1.0 - (1.0 / n_trials)))
    q2 = float(stats.norm.ppf(1.0 - (1.0 / (n_trials * e))))
    
    expected_max = mean_sr + std_sr * ((1.0 - euler_gamma) * q1 + euler_gamma * q2)
    return expected_max


def compute_deflated_sharpe_ratio(
    sr: float,
    all_sr_trials: Union[np.ndarray, List[float]],
    n_obs: int = 100,
    skew: float = 0.0,
    kurt: float = 3.0
) -> Dict[str, float]:
    """
    Computes the Deflated Sharpe Ratio (DSR) by deflating the nominal Sharpe ratio
    for the selection bias of picking the best performer out of N trials.
    
    Returns:
    - deflated_sharpe_ratio: Probability that true SR > expected maximum SR of N trials
    - expected_max_sharpe: Hurdle rate generated by multiple testing
    - nominal_sharpe: The tested strategy's Sharpe
    - p_value_deflated: 1.0 - DSR
    """
    arr = np.asarray(all_sr_trials, dtype=float)
    arr = arr[~np.isnan(arr)]
    n_trials = len(arr)
    
    if n_trials < 2:
        return {
            "deflated_sharpe_ratio": compute_probabilistic_sharpe_ratio(sr, 0.0, n_obs, skew, kurt),
            "expected_max_sharpe": 0.0,
            "nominal_sharpe": sr,
            "p_value_deflated": 1.0 - compute_probabilistic_sharpe_ratio(sr, 0.0, n_obs, skew, kurt)
        }
        
    var_sr = float(np.var(arr, ddof=1))
    mean_sr = float(np.mean(arr))
    
    expected_max_sr = compute_expected_max_sharpe(n_trials=n_trials, var_sr=var_sr, mean_sr=mean_sr)
    
    dsr = compute_probabilistic_sharpe_ratio(
        sr=sr,
        sr_benchmark=expected_max_sr,
        n_obs=n_obs,
        skew=skew,
        kurt=kurt
    )
    
    return {
        "deflated_sharpe_ratio": float(round(dsr, 4)),
        "expected_max_sharpe": float(round(expected_max_sr, 4)),
        "nominal_sharpe": float(round(sr, 4)),
        "p_value_deflated": float(round(1.0 - dsr, 4))
    }


def adjust_pvalues_bonferroni(p_values: Union[np.ndarray, List[float]]) -> np.ndarray:
    """
    Controls Family-Wise Error Rate (FWER) via Bonferroni correction:
    p_adj = min(1.0, p * N)
    """
    p_arr = np.asarray(p_values, dtype=float)
    n = len(p_arr)
    return np.clip(p_arr * n, 0.0, 1.0)


def adjust_pvalues_benjamini_hochberg(p_values: Union[np.ndarray, List[float]]) -> np.ndarray:
    """
    Controls False Discovery Rate (FDR) via the Benjamini-Hochberg (1995) procedure.
    Returns monotonic adjusted q-values.
    """
    p_arr = np.asarray(p_values, dtype=float)
    n = len(p_arr)
    if n == 0:
        return np.array([])
    
    sorted_indices = np.argsort(p_arr)
    sorted_p = p_arr[sorted_indices]
    
    # Calculate q-values: p * (n / rank)
    ranks = np.arange(1, n + 1)
    q_values = sorted_p * (n / ranks)
    
    # Enforce monotonicity in reverse order
    for i in range(n - 2, -1, -1):
        q_values[i] = min(q_values[i], q_values[i + 1])
        
    q_values = np.clip(q_values, 0.0, 1.0)
    
    # Restore original order
    adj_p = np.empty(n, dtype=float)
    adj_p[sorted_indices] = q_values
    return adj_p


def compute_institutional_risk_suite(
    trades: Union[List[float], np.ndarray],
    initial_capital: float = 10000.0,
    annualization_factor: float = np.sqrt(252 * 5)
) -> Dict[str, Any]:
    """
    Computes complete hedge-fund standard risk metrics from a series of net trade returns.
    """
    t_arr = np.asarray(trades, dtype=float)
    n_trades = len(t_arr)
    
    if n_trades == 0:
        return {
            "total_trades": 0,
            "win_rate_pct": 0.0,
            "net_pnl": 0.0,
            "return_pct": 0.0,
            "profit_factor": 0.0,
            "max_drawdown_pct": 0.0,
            "sharpe_ratio": 0.0,
            "sortino_ratio": 0.0,
            "calmar_ratio": 0.0,
            "omega_ratio": 0.0,
            "gain_to_pain_ratio": 0.0,
            "ulcer_index": 0.0,
            "martin_ratio": 0.0,
            "var_95_dollars": 0.0,
            "cvar_95_dollars": 0.0,
            "cdar_95_pct": 0.0,
            "return_skewness": 0.0,
            "return_kurtosis": 3.0,
            "tail_risk_ratio": 0.0,
            "max_consecutive_losses": 0,
            "max_consecutive_wins": 0,
            "psr_zero": 0.5
        }
        
    wins = t_arr[t_arr > 0]
    losses = t_arr[t_arr < 0]
    n_wins = len(wins)
    n_losses = len(losses)
    
    win_rate = (n_wins / n_trades) * 100.0
    gross_profit = float(np.sum(wins)) if n_wins > 0 else 0.0
    gross_loss = float(np.sum(np.abs(losses))) if n_losses > 0 else 0.0
    pf = (gross_profit / gross_loss) if gross_loss > 0 else (99.0 if gross_profit > 0 else 0.0)
    
    # Equity curve and underwater series
    equity_curve = np.zeros(n_trades + 1)
    equity_curve[0] = initial_capital
    equity_curve[1:] = initial_capital + np.cumsum(t_arr)
    
    peak_curve = np.maximum.accumulate(equity_curve)
    drawdowns_pct = (peak_curve - equity_curve) / np.where(peak_curve > 0, peak_curve, 1.0) * 100.0
    max_dd_pct = float(np.max(drawdowns_pct))
    
    net_pnl = float(np.sum(t_arr))
    return_pct = (net_pnl / initial_capital) * 100.0
    
    # 1. Sharpe Ratio
    mean_trade = float(np.mean(t_arr))
    std_trade = float(np.std(t_arr, ddof=1)) if n_trades > 1 else 0.0
    sharpe = (mean_trade / std_trade * annualization_factor) if std_trade > 1e-8 else 0.0
    
    # 2. Sortino Ratio (downside deviation MAR=0)
    downside_trades = np.minimum(0.0, t_arr)
    downside_std = float(np.sqrt(np.mean(downside_trades ** 2)))
    sortino = (mean_trade / downside_std * annualization_factor) if downside_std > 1e-8 else 0.0
    
    # 3. Calmar Ratio
    calmar = (return_pct / max_dd_pct) if max_dd_pct > 0.01 else (return_pct / 0.01)
    
    # 4. Omega Ratio (threshold = 0)
    omega = (gross_profit / gross_loss) if gross_loss > 0 else (99.0 if gross_profit > 0 else 0.0)
    
    # 5. Gain-to-Pain Ratio (Schwager)
    gain_to_pain = (net_pnl / gross_loss) if gross_loss > 0 else (99.0 if net_pnl > 0 else 0.0)
    
    # 6. Ulcer Index (UI) & Martin Ratio
    ulcer_index = float(np.sqrt(np.mean(drawdowns_pct ** 2)))
    martin = (return_pct / ulcer_index) if ulcer_index > 0.01 else (return_pct / 0.01)
    
    # 7. Value at Risk (VaR 95%) & Conditional VaR (CVaR 95% / Expected Shortfall)
    # Trade losses are negative numbers, VaR is reported as positive dollar amount at risk
    var_95 = float(-np.percentile(t_arr, 5)) if n_trades >= 5 else (float(-np.min(t_arr)) if n_trades > 0 else 0.0)
    tail_losses = t_arr[t_arr <= -var_95]
    cvar_95 = float(-np.mean(tail_losses)) if len(tail_losses) > 0 else var_95
    
    # 8. Conditional Drawdown at Risk (CDaR 95%)
    worst_dd_threshold = float(np.percentile(drawdowns_pct, 95))
    tail_dds = drawdowns_pct[drawdowns_pct >= worst_dd_threshold]
    cdar_95 = float(np.mean(tail_dds)) if len(tail_dds) > 0 else worst_dd_threshold
    
    # 9. Higher Statistical Moments (Skewness & Kurtosis)
    if n_trades >= 3 and std_trade > 1e-6:
        skew = float(stats.skew(t_arr))
    else:
        skew = 0.0
        
    if n_trades >= 4 and std_trade > 1e-6:
        raw_kurt = float(stats.kurtosis(t_arr, fisher=False))
    else:
        raw_kurt = 3.0
    
    # 10. Tail Risk Ratio (95th percentile gain / 5th percentile loss)
    p95_gain = float(np.percentile(t_arr, 95))
    p5_loss = float(abs(np.percentile(t_arr, 5)))
    tail_risk_ratio = (p95_gain / p5_loss) if p5_loss > 1e-6 else 1.0
    
    # 11. Maximum Consecutive Losses
    max_consec_losses = 0
    curr_losses = 0
    max_consec_wins = 0
    curr_wins = 0
    for t in t_arr:
        if t < 0:
            curr_losses += 1
            curr_wins = 0
            if curr_losses > max_consec_losses:
                max_consec_losses = curr_losses
        elif t > 0:
            curr_wins += 1
            curr_losses = 0
            if curr_wins > max_consec_wins:
                max_consec_wins = curr_wins
        else:
            curr_losses = 0
            curr_wins = 0
            
    # 12. Probabilistic Sharpe Ratio against benchmark SR* = 0
    psr_zero = compute_probabilistic_sharpe_ratio(
        sr=sharpe,
        sr_benchmark=0.0,
        n_obs=n_trades,
        skew=skew,
        kurt=raw_kurt
    )
    
    return {
        "total_trades": int(n_trades),
        "win_rate_pct": float(round(win_rate, 2)),
        "net_pnl": float(round(net_pnl, 2)),
        "return_pct": float(round(return_pct, 2)),
        "profit_factor": float(round(min(99.0, max(0.0, pf)), 2)),
        "max_drawdown_pct": float(round(max_dd_pct, 2)),
        "sharpe_ratio": float(round(sharpe, 2)),
        "sortino_ratio": float(round(sortino, 2)),
        "calmar_ratio": float(round(calmar, 2)),
        "omega_ratio": float(round(min(99.0, max(0.0, omega)), 2)),
        "gain_to_pain_ratio": float(round(min(99.0, max(-99.0, gain_to_pain)), 2)),
        "ulcer_index": float(round(ulcer_index, 2)),
        "martin_ratio": float(round(martin, 2)),
        "var_95_dollars": float(round(var_95, 2)),
        "cvar_95_dollars": float(round(cvar_95, 2)),
        "cdar_95_pct": float(round(cdar_95, 2)),
        "return_skewness": float(round(skew, 3)),
        "return_kurtosis": float(round(raw_kurt, 3)),
        "tail_risk_ratio": float(round(tail_risk_ratio, 2)),
        "max_consecutive_losses": int(max_consec_losses),
        "max_consecutive_wins": int(max_consec_wins),
        "psr_zero": float(round(psr_zero, 4))
    }
